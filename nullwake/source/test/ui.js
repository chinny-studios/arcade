// Menu checks: navigation, pilot unlocks, the hangar, stage locks, options, level-up keys, pause and results.
//   node test/smoke.mjs --no-start --steps test/ui.js
const fails = [], ok = (c, m) => { if (!c) fails.push(m); };
const q = (s) => document.querySelector(s), qa = (s) => [...document.querySelectorAll(s)];
const key = (code) => window.dispatchEvent(new KeyboardEvent('keydown', { code, bubbles: true }));
const S = NW.SAVE();
ok(q('#menu h1') && q('#menu h1').textContent === 'NULLWAKE', 'title screen');
key('ArrowDown'); ok(document.activeElement.dataset.act === 'hangar', 'arrow keys move focus to Hangar (got ' + document.activeElement.dataset.act + ')');
key('ArrowUp'); key('Enter');
ok(qa('#menu [data-act="pilot"]').length === 4, 'four pilot cards');
q('[data-arg="kade"]').click(); ok(!NW.SAVE().pilots.kade, 'Kade stays locked without gold');
NW.SAVE().gold = 5000; key('Escape'); q('[data-act="launch"]').click();
q('[data-arg="kade"]').click(); ok(NW.SAVE().pilots.kade && NW.SAVE().gold === 4400, 'Kade unlocked for 600 gold');
q('[data-arg="kade"]').click();
ok(qa('#menu [data-act="stage"]').length === 3, 'three stage cards');
q('[data-arg="s2"]').click(); ok(G.state !== 'play', 'Brood Moon locked at first');
q('[data-arg="s1"]').click(); ok(G.state === 'play' && G.pilotId === 'kade' && P.weapons[0].id === 'rail', 'run starts with Kade and the Rail Lance');
NW.mute();
NW.pause(); ok(G.state === 'pause' && q('[data-act="quit"]'), 'pause menu');
key('Escape'); ok(G.state === 'play', 'Esc resumes');
key('KeyP'); ok(G.state === 'pause', 'P pauses'); key('KeyP'); ok(G.state === 'play', 'P resumes');
const before = NW.stats().weapons.length + NW.stats().passives.length;
NW.levelUp(); ok(qa('#menu [data-act="pick"]').length === 3, 'three level-up cards');
key('Digit2'); ok(G.state === 'play', 'key 2 picks a card');
const after = NW.stats(); ok(after.weapons.length + after.passives.length >= before, 'pick applied');
NW.give('lash', 8); NW.give('nanite', 1);
NW.chest('elite'); ok(P.weapons.some((w) => w.id === 'siphon') && q('#menu h2').textContent.includes('Evolution'), 'chest evolves Arc Lash into Siphon Lash');
q('[data-act="resume"]').click();
NW.end(false); ok(G.state === 'over' && q('[data-act="retry"]'), 'results screen');
const runs = NW.SAVE().totals.runs; ok(runs === 1, 'run counted');
q('[data-act="title"]').click(); ok(G.state === 'title', 'back to title');
q('[data-act="hangar"]').click();
const g0 = NW.SAVE().gold; q('[data-arg="hull"]').click(); ok(NW.SAVE().meta.hull === 1 && NW.SAVE().gold === g0 - 200, 'bought Reinforced Hull rank 1');
q('[data-arg="hull"]').click(); ok(NW.SAVE().meta.hull === 2 && NW.SAVE().gold === g0 - 600, 'rank 2 costs 400');
q('[data-act="refund"]').click(); ok(!NW.SAVE().meta.hull && NW.SAVE().gold === g0, 'refund returns all gold');
key('Escape'); q('[data-act="codex"]').click(); ok(qa('#menu .evo-row').length === 24, 'codex rows (got ' + qa('#menu .evo-row').length + ')');
ok(q('#menu .codex').textContent.includes('Siphon Lash'), 'codex names a seen evolution');
key('Escape'); q('[data-act="options"]').click(); q('[data-arg="sfx-"]').click(); ok(Math.abs(NW.SAVE().opts.sfx - 0.7) < 1e-9 || NW.SAVE().opts.sfx === 0, 'sfx down');
q('[data-arg="nums"]').click(); ok(NW.SAVE().opts.nums === 0, 'damage numbers off');
key('Escape'); ok(G.state === 'title', 'options back to title');
ok(JSON.parse(localStorage.getItem('nullwake.save.v1')).pilots.kade === 1, 'save written');
NW.SAVE().cleared.s1 = 1; q('[data-act="launch"]').click(); q('[data-arg="ryn"]').click(); q('[data-arg="s2"]').click();
ok(G.state === 'play' && G.stageId === 's2', 'Brood Moon opens after a clear of Kessler Drift');
return fails.length ? fails : 'all UI checks passed';
