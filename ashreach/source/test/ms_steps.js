const P = AR.quick('trooper');
const ms = AR.ms;
AR.changeZone('halden');
const out = {};
out.zone = AR.ZONE.id;
out.npcs = AR.ents('npc').slice(0, 12).map(e => e.name);
const offers = ms.requestMissions(null, { easy_hard: -1 });
out.offers = offers.map(o => o.type + ' | ' + o.title + ' @' + o.location.zone + ' ' + Math.round(o.location.x) + ',' + Math.round(o.location.z));
const m = ms.acceptMission(null, offers[0]);
out.accepted = !!m && P.char.missions.length;
AR.changeZone(m.location.zone);
const door = AR.ents().find(e => e.name.startsWith('Mission:'));
out.door = door;
out.beacons = ms.MS.beacons.length;
const dent = AR.ENTS.find(e => e.name.startsWith('Mission:'));
AR.tp(dent.pos.x + 3, dent.pos.z + 3);
AR.sim(1);
await shot('ms_door');
AR.interact(dent);
out.afterDoor = AR.ZONE.id;
return out;
