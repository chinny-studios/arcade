// Screenshots of every UI screen/window via test/ui_view.html (served over a throwaway local http server).
//   node test/ui_shots.mjs [--size 1280x720] [--only name,name]   -> test/out/ui_<name>.png
import { createRequire } from 'module';
import http from 'http';
import fs from 'fs';
import path from 'path';
import url from 'url';
const require = createRequire(import.meta.url);
let pw;
try { pw = require('playwright'); } catch { pw = require('/opt/node22/lib/node_modules/playwright'); }
const here = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const [W, H] = opt('--size', '1280x720').split('x').map(Number);
const only = opt('--only', '') ? opt('--only').split(',') : null;
const out = path.join(here, 'out');
fs.mkdirSync(out, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png' };
const server = http.createServer((req, res) => {
  const p = path.join(root, decodeURIComponent(req.url.split('?')[0]));
  if (!p.startsWith(root) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { 'content-type': types[path.extname(p)] || 'application/octet-stream' });
  fs.createReadStream(p).pipe(res);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const port = server.address().port;
const browser = await pw.chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: W, height: H } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + (e.stack || e.message)));
await page.goto('http://127.0.0.1:' + port + '/test/ui_view.html');
await page.waitForFunction(() => window.UIV && window.UIV.ready, null, { timeout: 60000 });
const ev = (fn, a) => page.evaluate(fn, a);
const shot = async (name) => { if (!only || only.includes(name)) { await page.waitForTimeout(350); await page.screenshot({ path: path.join(out, 'ui_' + name + '.png') }); console.log('shot', name); } };
const hover = async (sel) => { const p = await ev((s) => window.UIV.hover(s), sel); if (p) await page.mouse.move(p.x, p.y); await page.waitForTimeout(150); };

